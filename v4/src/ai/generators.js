/**
 * V4 — Deterministic code generators.
 *
 * Every generator here is a pure, offline template expander: the same input
 * always produces byte-identical output, no network call, no API key, no
 * model. The generated code is real, runnable ES module code that imports the
 * V4 core through correct relative paths.
 *
 * The generator knows where the generated project lives (`projectRoot`,
 * relative to the V4 root) so it can compute the import prefix for the files
 * it emits.
 */

import { posix, relative, resolve, sep } from 'node:path';

import { V4_ROOT } from '../assets/catalogue.js';

/* ------------------------------------------------------------------ utils */

/** Serialise a JS value as source code. */
function lit(value) {
  if (value === undefined) return 'undefined';
  if (value === null) return 'null';
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return `[${value.map(lit).join(', ')}]`;
  if (typeof value === 'object') {
    const parts = Object.entries(value).map(([k, v]) => `${JSON.stringify(k)}: ${lit(v)}`);
    return `{ ${parts.join(', ')} }`;
  }
  return 'null';
}

/** A file-safe slug from any name. */
export function slugify(name) {
  return String(name ?? '')
    .trim()
    .replace(/[^A-Za-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase() || 'untitled';
}

/** `demo-scene` -> `DemoScene` */
export function pascalCase(name) {
  return String(name ?? '')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('') || 'Untitled';
}

/** `demo-scene` -> `demoScene` */
export function camelCase(name) {
  const pascal = pascalCase(name);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

/**
 * The relative import prefix from a generated file to the V4 `src/` folder.
 * `projectRoot` is relative to the V4 root.
 */
export function importPrefix(projectRoot, filePath) {
  const from = resolve(V4_ROOT, projectRoot, posix.dirname(filePath));
  const to = resolve(V4_ROOT, 'src');
  const rel = relative(from, to).split(sep).join('/');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

/** A generated file descriptor. */
function file(path, content) {
  return { path, content };
}

/** A standard file header. */
function header(title) {
  return `/**\n * ${title}\n *\n * Generated by the V4 deterministic generator (v4/src/ai/generators.js).\n * Edit freely — regenerating overwrites this file.\n */\n`;
}

/* ----------------------------------------------------------- component gen */

const FIELD_DEFAULTS = {
  number: 0,
  string: '',
  boolean: false,
  array: [],
  object: {},
};

function fieldDefault(field) {
  if (field && Object.prototype.hasOwnProperty.call(field, 'default')) return field.default;
  return FIELD_DEFAULTS[field?.type] ?? null;
}

/**
 * Generate a component module.
 *
 * @param {{name:string, fields?:Array<{name:string,type?:string,default?:any}>, projectRoot?:string}} opts
 * @returns {{files:Array, notes:string[]}}
 */
export function generateComponent({ name, fields = [], projectRoot } = {}) {
  const slug = slugify(name);
  const pascal = pascalCase(name);
  const cleanFields = fields.filter((f) => f && f.name);
  const path = `src/components/${slug}.js`;
  const core = importPrefix(projectRoot ?? `generated/${slug}`, path);

  const defaults = cleanFields.map((f) => `  ${JSON.stringify(f.name)}: ${lit(fieldDefault(f))},`).join('\n');

  const content = `${header(`${pascal} component`)}
import { createRegistry } from '${core}/core/serialization.js';

/** The component type as it is registered in the serialisation registry. */
export const COMPONENT_TYPE = ${lit(slug)};

/** The default data for a fresh ${slug} component. */
export const ${pascal}Defaults = {
${defaults || '  // no fields declared'
}
};

/**
 * Build a ${slug} component instance. Unknown fields are dropped.
 */
export function create${pascal}Component(data = {}) {
  const out = { ...${pascal}Defaults };
  for (const key of Object.keys(${pascal}Defaults)) {
    if (data[key] !== undefined) out[key] = data[key];
  }
  return out;
}

/**
 * Register the ${slug} component on a registry (defaults to a fresh one).
 */
export function register${pascal}Component(registry = createRegistry()) {
  registry.register(COMPONENT_TYPE, {
    defaults: () => create${pascal}Component(),
    serialize: (data) => ({ ...create${pascal}Component(data) }),
    deserialize: (raw) => create${pascal}Component(raw ?? {}),
  });
  return registry;
}
`;

  return {
    files: [file(path, content)],
    notes: [
      `Component "${slug}" with ${cleanFields.length} field(s).`,
      `Registered as "${slug}" — save files using this type will round-trip.`,
    ],
  };
}

