/**
 * Generate an NPC behaviour.
 *
 * @param {{name:string, states?:Array|object, projectRoot?:string}} opts
 * @returns {{files:Array, notes:string[]}}
 */
export function generateNpcBehaviour({ name, states = [], projectRoot } = {}) {
  const slug = slugify(name);
  const pascal = pascalCase(name);
  const path = `src/npc/${slug}.js`;
  const core = importPrefix(projectRoot ?? `generated/${slug}`, path);

  let list = Array.isArray(states) ? states.map((s) => ({ ...s })) : Object.entries(states).map(([n, d]) => ({ name: n, ...d }));
  if (!list.length) list = [{ name: 'idle', speed: 0, sight: 0 }];
  if (!list.some((s) => s.name === 'idle')) list.unshift({ name: 'idle', speed: 0, sight: 0 });
  const needsCombat = list.some((s) => (s.sight ?? 0) > 0);
  if (needsCombat) {
    if (!list.some((s) => s.name === 'chase')) list.push({ name: 'chase', speed: 3, sight: 0, fallback: 'idle' });
    if (!list.some((s) => s.name === 'attack')) list.push({ name: 'attack', speed: 0, sight: 0, attack: 1.5, fallback: 'idle' });
  }

  const stateEntries = list.map((s) => {
    const parts = [`name: ${lit(s.name)}`, `speed: ${s.speed ?? 0}`, `sight: ${s.sight ?? 0}`];
    if (s.attack !== undefined) parts.push(`attack: ${s.attack}`);
    if (s.fallback !== undefined) parts.push(`fallback: ${lit(s.fallback)}`);
    return `  { ${parts.join(', ')} },`;
  }).join('\n');

  const content = `${header(`${pascal} NPC behaviour`)}
import { Events } from '${core}/core/events.js';
import { setPosition } from '${core}/core/transform.js';

/** The states this behaviour can be in. */
export const ${pascal.toUpperCase().replace(/[^A-Z0-9]+/g, '_')}_STATES = [
${stateEntries}
];

/**
 * A small, deterministic behaviour machine.
 *
 * The state changes are driven by numbers the caller supplies (a distance to
 * the target, a direction to walk), so the behaviour can be replayed exactly
 * in a test.
 */
export function create${pascal}Behaviour({ world = null, bus = null, entityId = null } = {}) {
  const states = ${pascal.toUpperCase().replace(/[^A-Z0-9]+/g, '_')}_STATES;
  const known = new Set(states.map((s) => s.name));
  /** How far the NPC notices a target, and how close it can strike. */
  const senses = states.reduce((n, s) => Math.max(n, s.sight ?? 0), 0);
  const reach = states.reduce((n, s) => Math.max(n, s.attack ?? 0), 0);
  let current = states[0].name;
  let elapsed = 0;

  /** Move to a state, emitting NPC_STATE when it actually changes. */
  function setState(next) {
    if (!known.has(next) || next === current) return false;
    const from = current;
    current = next;
    elapsed = 0;
    if (bus) bus.emit(Events.NPC_STATE, { entityId, from, to: next });
    return true;
  }

  function stateDef() {
    return states.find((s) => s.name === current) ?? states[0];
  }

  /**
   * Advance the behaviour.
   *
   * @param {number} dt
   * @param {{distance?:number, direction?:number[]}} context
   */
  function update(dt = 0, context = {}) {
    elapsed += dt;
    const def = stateDef();
    const distance = context.distance ?? Infinity;
    let next = current;
    if (reach > 0 && distance <= reach) next = 'attack';
    else if (senses > 0 && distance <= senses) next = 'chase';
    else if (current === 'chase' || current === 'attack') next = def.fallback ?? 'idle';
    setState(next);

    const active = stateDef();
    const speed = active.speed ?? 0;
    if (speed > 0 && world && entityId !== null) {
      const direction = context.direction ?? [0, 0, 0];
      const transform = world.getComponent(entityId, 'transform');
      if (transform) {
        const p = transform.position;
        setPosition(
          transform,
          p[0] + direction[0] * speed * dt,
          p[1] + direction[1] * speed * dt,
          p[2] + direction[2] * speed * dt,
        );
      }
    }
    return current;
  }

  return {
    get state() { return current; },
    get elapsed() { return elapsed; },
    states: () => states.map((s) => s.name),
    setState,
    update,
  };
}
`;

  return {
    files: [file(path, content)],
    notes: [
      `NPC behaviour "${slug}" with ${list.length} state(s).`,
      'State changes are driven by caller-supplied distances, so the behaviour replays identically in a test.',
    ],
  };
}

