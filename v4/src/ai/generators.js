/**
 * Generate a test module for one of the engine modules.
 *
 * @param {{moduleName:string, projectRoot?:string}} opts
 * @returns {{files:Array, notes:string[]}}
 */
export function generateTests({ moduleName, projectRoot } = {}) {
  const slug = slugify(moduleName);
  const path = `tests/${slug}.test.mjs`;
  const core = importPrefix(projectRoot ?? `generated/${slug}`, path);
  const known = KNOWN_TESTS[slug];

  let content;
  let notes;
  if (known) {
    const imports = known.imports.replaceAll('__CORE__', core);
    content = `${header(`${slug} tests`)}
import test from 'node:test';
import assert from 'node:assert/strict';

${imports}

test('${slug} behaves as the engine expects', () => {
${known.body}
});
`;
    notes = [`Generated a focused test for the "${slug}" core module.`];
  } else {
    content = `${header(`${slug} tests`)}
import test from 'node:test';
import assert from 'node:assert/strict';

test('${slug} exports a usable API', async () => {
  const mod = await import('../src/${slug}.js');
  const exported = Object.keys(mod).filter((key) => typeof mod[key] === 'function');
  assert.ok(exported.length > 0, 'expected ${slug} to export at least one function');
});
`;
    notes = [`No specific template for "${slug}" — generated an API smoke test instead.`];
  }

  return { files: [file(path, content)], notes };
}

