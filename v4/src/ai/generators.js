/**
 * Generate a whole project: the entry point, the scene, the tests and the
 * package metadata.
 *
 * @param {{name:string, template?:string, projectRoot?:string}} opts
 * @returns {{files:Array, notes:string[]}}
 */
export function generateProject({ name, template = 'minimal', projectRoot } = {}) {
  const slug = slugify(name);
  const pascal = pascalCase(name);
  const root = projectRoot ?? `generated/${slug}`;
  const chosen = TEMPLATES[template] ?? TEMPLATES.minimal;
  const actualTemplate = TEMPLATES[template] ? template : 'minimal';

  const scene = generateScene({ name: slug, entities: chosen.entities, projectRoot: root });
  const tests = generateTests({ moduleName: 'ecs', projectRoot: root });
  const mainPath = 'src/main.js';
  const core = importPrefix(root, mainPath);

  const main = `${header(`${pascal} — entry point`)}
import { createEventBus, Events } from '${core}/core/events.js';
import { createLogger } from '${core}/core/log.js';
import { createClock } from '${core}/core/time.js';
import { serializeScene } from '${core}/core/serialization.js';
import { create${pascal}Scene } from './scenes/${slug}.js';

/**
 * Boot the project: build the scene, wire the services and return them.
 */
export function boot() {
  const bus = createEventBus();
  const logger = createLogger({ level: 'info', bus });
  const clock = createClock();
  const { world, registry } = create${pascal}Scene();

  bus.emit(Events.WORLD_READY, { entities: world.entityCount });
  logger.info('${slug} ready', { entities: world.entityCount });

  return {
    bus,
    logger,
    clock,
    world,
    registry,
    /** A JSON snapshot of the scene. */
    snapshot: () => serializeScene(world, registry, '${slug}'),
  };
}

export default boot;
`;

  const html = `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${pascal}</title>
  </head>
  <body>
    <canvas id="stage" width="1280" height="720"></canvas>
    <script type="module">
      import { boot } from './src/main.js';
      const app = boot();
      globalThis.v4App = app;
    </script>
  </body>
</html>
`;

  const pkg = `${JSON.stringify({
    name: slug,
    version: '0.1.0',
    private: true,
    type: 'module',
    description: `${pascal} — generated with the V4 deterministic generator.`,
    scripts: { test: 'node --test tests/' },
    dependencies: { three: '^0.169.0' },
  }, null, 2)}\n`;

  const readme = `# ${pascal}

Generated with the V4 deterministic generator (template: \`${actualTemplate}\`).

## Layout

| file | what it is |
| --- | --- |
| \`src/main.js\` | boots the scene and returns the world, bus, logger and clock |
| \`src/scenes/${slug}.js\` | the scene: ${chosen.entities.length} entity/entities |
| \`tests/${slug}.test.mjs\` | the generated test module |

The template is **${actualTemplate}** — ${chosen.description}

## Run the tests

\`\`\`sh
node --test tests/
\`\`\`
`;

  return {
    files: [
      file('package.json', pkg),
      file('index.html', html),
      file(mainPath, main),
      ...scene.files,
      ...tests.files,
      file('README.md', readme),
    ],
    notes: [
      `Project "${slug}" from template "${actualTemplate}".`,
      chosen.description,
      'All generated code is deterministic: the same input always produces the same files.',
    ],
  };
}

