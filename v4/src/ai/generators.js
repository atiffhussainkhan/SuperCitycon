/**
 * Generate a scene module.
 *
 * @param {{name:string, entities?:Array, projectRoot?:string}} opts
 * @returns {{files:Array, notes:string[]}}
 */
export function generateScene({ name, entities = [], projectRoot } = {}) {
  const slug = slugify(name);
  const pascal = pascalCase(name);
  const path = `src/scenes/${slug}.js`;
  const core = importPrefix(projectRoot ?? `generated/${slug}`, path);

  const blocks = entities.map((entity, index) => {
    const entityName = entity?.name ?? `Entity${index + 1}`;
    const tags = entity?.tags ?? [];
    const components = entity?.components ?? {};
    const entries = Object.entries(components).map(([type, data]) => {
      return `    '${type}': ${lit(data)},`;
    }).join('\n');
    return `  add(${lit(entityName)}, ${lit(tags)}, {\n${entries}\n  });`;
  }).join('\n\n');

  const content = `${header(`${pascal} scene`)}
import { createWorld } from '${core}/core/ecs.js';
import { createRegistry } from '${core}/core/serialization.js';

/** The scene's name as it appears in the scene manager. */
export const SCENE_NAME = ${lit(slug)};

/**
 * Build the ${slug} scene: a fresh world plus a registry that knows the
 * built-in component types.
 */
export function create${pascal}Scene() {
  const world = createWorld();
  const registry = createRegistry();
  registry.registerBuiltins();

  /** Create an entity and attach its components. */
  const add = (entityName, tags, components) => {
    const entity = world.createEntity({ name: entityName, tags });
    for (const [type, data] of Object.entries(components)) {
      world.addComponent(entity.id, type, { ...(registry.defaults(type) ?? {}), ...data });
    }
    return entity;
  };

${blocks || '  // no entities declared'}

  return { world, registry, sceneName: SCENE_NAME };
}

export default create${pascal}Scene;
`;

  return {
    files: [file(path, content)],
    notes: [
      `Scene "${slug}" with ${entities.length} entity/entities.`,
      'Entities are created through the registry defaults, so a missing field falls back to the built-in default.',
    ],
  };
}

