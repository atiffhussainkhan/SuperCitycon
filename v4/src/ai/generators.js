/**
 * Generate an animation controller.
 *
 * @param {{name?:string, states?:object|Array, projectRoot?:string}} opts
 * @returns {{files:Array, notes:string[]}}
 */
export function generateAnimationController({ name = 'controller', states = {}, projectRoot } = {}) {
  const slug = slugify(name);
  const pascal = pascalCase(name);
  const constName = `${pascal.toUpperCase().replace(/[^A-Z0-9]+/g, '_')}_STATES`;
  const path = `src/anim/${slug}.js`;
  const core = importPrefix(projectRoot ?? `generated/${slug}`, path);

  const normalised = Array.isArray(states)
    ? Object.fromEntries(states.map((s) => [s.name, s]))
    : { ...states };
  const stateNames = Object.keys(normalised);
  if (!stateNames.length) normalised.idle = { clips: ['Idle'], loop: true, speed: 1 };

  const stateEntries = Object.entries(normalised).map(([state, def]) => {
    const clips = def.clips ?? def.clip ?? [state];
    return `  ${lit(state)}: { clips: ${lit([].concat(clips))}, loop: ${def.loop === false ? 'false' : 'true'}, speed: ${def.speed ?? 1} },`;
  }).join('\n');

  const base = stateNames[0];
  const transitions = [];
  for (const state of stateNames.slice(1)) {
    transitions.push(`  { from: ${lit(base)}, to: ${lit(state)}, when: ${lit(state)}, fade: 0.2 },`);
    transitions.push(`  { from: ${lit(state)}, to: ${lit(base)}, when: ${lit(`!${state}`)}, fade: 0.2 },`);
  }

  const content = `${header(`${pascal} animation controller`)}
import { createAnimator } from '${core}/anim/animator.js';
import { Events } from '${core}/core/events.js';

/** The states this controller understands. */
export const ${constName} = {
${stateEntries}
};

/** The transitions between them — a condition name per transition. */
export const ${pascal.toUpperCase().replace(/[^A-Z0-9]+/g, '_')}_TRANSITIONS = [
${transitions.join('\n') || '  // no transitions'}
];

/**
 * Create the controller for one character.
 *
 * @param {{root:object, clips?:Array, bus?:object, entityId?:number}} opts
 */
export function create${pascal}Controller({ root, clips = [], bus = null, entityId = null } = {}) {
  const animator = createAnimator({
    root,
    clips,
    bus,
    states: ${constName},
    transitions: ${pascal.toUpperCase().replace(/[^A-Z0-9]+/g, '_')}_TRANSITIONS,
    entityId,
  });

  return {
    animator,
    get state() { return animator.state; },
    get previousState() { return animator.previousState; },
    states: () => animator.states(),
    clips: () => animator.clips(),
    setCondition: (name, value) => animator.setCondition(name, value),
    play: (state, fade = 0.2) => animator.play(state, fade),
    update: (dt) => animator.update(dt),
    dispose: () => animator.dispose(),
  };
}

/** The event the controller emits when the state changes. */
export const STATE_EVENT = Events.ANIMATION_STATE;
`;

  return {
    files: [file(path, content)],
    notes: [
      `Animation controller "${slug}" with ${Object.keys(normalised).length} state(s).`,
      'Clip names are matched case-insensitively against the model\'s real clips, exactly like the built-in animator.',
    ],
  };
}

